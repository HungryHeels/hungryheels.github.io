// Build the built-in menu seed from pages the student saved by hand.
// Usage: tsx scripts/build-seed.ts <folder-with-saved-pages> [more folders...]
// Reads .webarchive/.html/.htm files. Never fetches anything from dining.unc.edu.
import { readFileSync, readdirSync, statSync, writeFileSync, existsSync } from 'node:fs';
import { join } from 'node:path';
import { gzipSync } from 'node:zlib';
import { readPageFile } from '../src/sources/bplist.ts';
import { PageError, parseUncPage } from '../src/sources/unc-page.ts';
import { borrowNutrition, parseSnapshotText } from '../src/core/borrow.ts';
import { EAT_UNC_META } from '../src/sources/snapshot-data.ts';
import { encodeSeed } from '../src/core/seed.ts';
import type { MenuDay } from '../src/core/types.ts';

const dirs = process.argv.slice(2);
if (!dirs.length) { console.error('Give at least one folder of saved pages.'); process.exit(2); }
const times: Record<string, string> = existsSync('data/saved-times.json') ? JSON.parse(readFileSync('data/saved-times.json', 'utf8')) : {};
const snapPath = 'data/eatunc-2026-11-05.txt';
const snapshot = existsSync(snapPath) ? parseSnapshotText(readFileSync(snapPath, 'utf8')) : [];

const days = new Map<string, MenuDay>();
const report: string[] = [];
for (const dir of dirs) {
  for (const f of readdirSync(dir).sort()) {
    if (!/\.(webarchive|html?)$/i.test(f)) continue;
    const path = join(dir, f);
    try {
      const modified = statSync(path).mtime.toISOString();
      const d = parseUncPage(readPageFile(new Uint8Array(readFileSync(path))), { source: "dining.unc.edu page saved by hand by this app's author", retrievedAt: modified, fileName: f });
      const t = times[`${d.hall}:${d.date}`];
      if (t) d.provenance.retrievedAt = t;
      const { unknownClasses, ...day } = d as MenuDay & { unknownClasses: string[] };
      if (unknownClasses.length) report.push(`${f}: unknown classes ${unknownClasses.join(', ')}`);
      if (snapshot.length) borrowNutrition(day as MenuDay, snapshot, EAT_UNC_META);
      days.set(`${d.hall}:${d.date}`, day as MenuDay);
    } catch (e) {
      report.push(`${f}: ${e instanceof PageError || e instanceof Error ? e.message : e}`);
    }
  }
}
const list = [...days.values()].sort((a, b) => (a.hall + a.date < b.hall + b.date ? -1 : 1));
const seed = encodeSeed(list);
const json = JSON.stringify(seed);
const gz = gzipSync(Buffer.from(json), { level: 9 });
writeFileSync('src/client/seed-data.ts', `// GENERATED by scripts/build-seed.ts. Do not edit.\nexport const SEED_B64 = '${gz.toString('base64')}';\n`);
console.log(`days: ${list.length} (with menus: ${list.filter(d => !d.noMenuPosted).length}, no menu posted: ${list.filter(d => d.noMenuPosted).length})`);
console.log(`json ${(json.length / 1e6).toFixed(2)} MB -> gzip ${(gz.length / 1e3).toFixed(0)} KB, ${Object.keys(seed.items).length} unique items`);
for (const l of report) console.log('NOTE', l);

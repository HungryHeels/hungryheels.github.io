// Turns data/restaurants/<id>/{source.json,components.csv} into src/client/restaurant-data.ts (embedded in the app).
// A folder without both files is "pending" (no data shipped). A folder whose files break any import rule FAILS the
// build: nothing half-valid is shipped. Reads only local files; no network.
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { importRestaurant } from '../src/sources/restaurant-import.ts';
import { RESTAURANT_IDS, type RestaurantMenu } from '../src/core/restaurant.ts';

export const RESTAURANTS_DIR = 'data/restaurants';
export interface FolderResult { id: string; status: 'built-in' | 'pending'; menu: RestaurantMenu | null; errors: string[]; warnings: string[] }

export function readRestaurantFolders(dir = RESTAURANTS_DIR): FolderResult[] {
  return RESTAURANT_IDS.map(id => {
    const src = join(dir, id, 'source.json'), csv = join(dir, id, 'components.csv');
    const has = [existsSync(src), existsSync(csv)];
    if (!has[0] && !has[1]) return { id, status: 'pending' as const, menu: null, errors: [], warnings: [] };
    if (!has[0] || !has[1]) return { id, status: 'pending' as const, menu: null, errors: [`${id}: needs both source.json and components.csv (found only ${has[0] ? 'source.json' : 'components.csv'}).`], warnings: [] };
    const r = importRestaurant(readFileSync(src, 'utf8'), readFileSync(csv, 'utf8'), id);
    return { id, status: r.menu ? 'built-in' as const : 'pending' as const, menu: r.menu, errors: r.errors.map(e => `${id}: ${e}`), warnings: r.warnings.map(w => `${id}: ${w}`) };
  });
}

export function writeRestaurantData(dir = RESTAURANTS_DIR, out = 'src/client/restaurant-data.ts'): FolderResult[] {
  const res = readRestaurantFolders(dir);
  const errors = res.flatMap(r => r.errors);
  if (errors.length) throw new Error('Restaurant data has problems; nothing was built:\n  ' + errors.join('\n  '));
  for (const r of res) for (const w of r.warnings) console.warn('warning: ' + w);
  const menus = res.filter(r => r.menu).map(r => r.menu);
  const text = '// Generated by scripts/build-restaurants.ts from data/restaurants/. Do not edit by hand.\n' +
    "import type { RestaurantMenu } from '../core/restaurant.ts';\n" +
    `export const RESTAURANT_DATA: RestaurantMenu[] = ${JSON.stringify(menus)};\n`;
  writeFileSync(out, text);
  console.log('restaurants: ' + res.map(r => `${r.id} ${r.status}${r.menu ? ` (${r.menu.components.length} components)` : ''}`).join(', '));
  return res;
}

if (process.argv[1] && /build-restaurants\.ts$/.test(process.argv[1])) writeRestaurantData();
